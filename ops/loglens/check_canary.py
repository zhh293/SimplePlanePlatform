"""Verify indexing, failure recovery and isolation using synthetic records only."""

from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import secrets
import subprocess
import tempfile
from unittest.mock import patch
from urllib.error import HTTPError

from ship import Elasticsearch, Ship


def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="http://127.0.0.1:9200")
    parser.add_argument("--run", nargs=argparse.REMAINDER, help="Run tests against the prepared fixture before cleanup")
    parser.add_argument("--relay-fixture", type=Path, help="Directory with logs generated by check_proxy.py")
    args = parser.parse_args()
    prefix = "sp-log-canary-" + secrets.token_hex(6)
    es = Elasticsearch(args.url, prefix, canary=True)
    now = datetime.now(timezone.utc)
    index = prefix + "-" + now.strftime("%Y.%m.%d")
    first = hashlib.sha256(b"test-issuer\0alice").hexdigest()
    second = hashlib.sha256(b"test-issuer\0bob").hexdigest()
    event = {"eventTime": int(now.timestamp() * 1000), "targetHost": "api.example.test", "targetPort": 443,
             "transport": "http3", "connectionId": "fixture-shared", "uplinkBytes": 19, "downlinkBytes": 39}
    fixture = [
        dict(event, kind="SESSION_ACTIVE", eventId="evt-1", proxySessionId="alice-1", accountId=first),
        dict(event, kind="SESSION_CONNECT_FAILED", eventId="evt-2", proxySessionId="bob-1", accountId=second),
        dict(event, kind="SESSION_CLOSED", eventId="evt-3", proxySessionId="alice-1", accountId=first),
        dict(event, kind="TRAFFIC_SAMPLE", eventId="evt-4", proxySessionId="alice-1", accountId=first),
    ]
    log = {"eventTime": event["eventTime"], "eventId": "evt-5", "level": "WARN", "message": "fixture connection timeout",
           "mdc": {"sp.accountId": second, "sp.proxySessionId": "bob-1", "token": "synthetic-hidden-token"}}

    def query(clause, **extra):
        body = {"query": clause, **extra}
        return es.request("POST", "/" + index + "/_search", json.dumps(body).encode())

    es.prepare()
    try:
        with tempfile.TemporaryDirectory(prefix="log-center-fixture-") as name:
            root = Path(name)
            session = root / "proxy" / "session"
            session.mkdir(parents=True)
            (session / "telemetry-0001.jsonl").write_text("".join(json.dumps(row) + "\n" for row in fixture), encoding="utf-8")
            (session / "captured-0001.jsonl").write_text(json.dumps(log), encoding="utf-8")
            ship = Ship(root, "test-node", root / "first.sqlite", 14, es)
            with patch.object(es, "bulk", side_effect=OSError("simulated Elasticsearch outage")):
                try:
                    ship.scan()
                except OSError:
                    pass
                else:
                    raise AssertionError("outage should stop the batch")
            assert ship.db.execute("SELECT count(*) FROM checkpoint").fetchone()[0] == 0
            assert ship.scan() == 3
            with (session / "captured-0001.jsonl").open("a") as stream:
                stream.write("\n")
            assert ship.scan() == 1
            assert ship.scan() == 0
            ship.db.close()
            replay = Ship(root, "test-node", root / "second.sqlite", 14, es)
            assert replay.scan() == 4
            replay.db.close()

        es.request("POST", "/" + index + "/_refresh", None)
        assert query({"match_all": {}})["hits"]["total"]["value"] == 4
        filters = [{"term": {"account_id": second}}, {"term": {"domain_suffix": "example.test"}}]
        hit = query({"bool": {"filter": filters}})["hits"]["hits"]
        assert len(hit) == 1 and hit[0]["_source"]["event_kind"] == "SESSION_CONNECT_FAILED"
        assert query({"term": {"account_id": first}})["hits"]["total"]["value"] == 2
        body_result = query({"match_phrase": {"message": "connection timeout"}})["hits"]["hits"]
        assert len(body_result) == 1 and "synthetic-hidden-token" not in json.dumps(body_result)
        assert query({"term": {"proxy_session_id": "bob-1"}})["hits"]["total"]["value"] == 2

        pit = es.request("POST", "/" + index + "/_pit?keep_alive=30s", None)["id"]
        try:
            page = {"pit": {"id": pit, "keep_alive": "30s"}, "size": 2, "sort": [{"@timestamp": "asc"}]}
            first_page = es.request("POST", "/_search", json.dumps(page).encode())
            pit = first_page.get("pit_id", pit)
            page["pit"]["id"] = pit
            page["search_after"] = first_page["hits"]["hits"][-1]["sort"]
            second_page = es.request("POST", "/_search", json.dumps(page).encode())
            pit = second_page.get("pit_id", pit)
            assert len({row["_id"] for reply in (first_page, second_page) for row in reply["hits"]["hits"]}) == 4
        finally:
            es.request("DELETE", "/_pit", json.dumps({"id": pit}).encode())
        print("PASS recovery, partial line, replay deduplication, account scope, domain suffix, phrase, session and PIT pagination")
        if args.run:
            subprocess.run(args.run, check=True, env=dict(os.environ, SP_TEST_LOG_ES=args.url, SP_TEST_LOG_PREFIX=prefix))
        if args.relay_fixture:
            with tempfile.TemporaryDirectory(prefix="log-center-relay-") as name:
                relay = Ship(args.relay_fixture, "relay-canary", Path(name) / "relay.sqlite", 1, es)
                assert relay.scan() > 0
                relay.db.close()
            es.request("POST", "/" + index + "/_refresh", None)
            for account in ("a" * 64, "b" * 64, None):
                clauses = [{"term": {"node_id": "relay-canary"}}, {"term": {"target_ip": "192.0.2.73"}}]
                missing = []
                if account:
                    clauses.append({"term": {"account_id": account}})
                else:
                    missing.append({"exists": {"field": "account_id"}})
                rows = query({"bool": {"filter": clauses, "must_not": missing}}, size=50)["hits"]["hits"]
                assert {"SESSION_ACTIVE", "SESSION_CONNECT_FAILED", "SESSION_CLOSED"} <= {
                    hit["_source"]["event_kind"] for hit in rows
                }
                session = next(hit["_source"]["proxy_session_id"] for hit in rows
                               if hit["_source"]["event_kind"] == "SESSION_CONNECT_FAILED")
                log_clauses = [{"term": {"node_id": "relay-canary"}}, {"term": {"proxy_session_id": session}},
                               {"term": {"dataset": "application"}}]
                assert query({"bool": {"filter": log_clauses}})["hits"]["total"]["value"] >= 1
            print("PASS actual LogLens relay fixture indexed and linked by account, target and session")
    finally:
        try:
            es.request("DELETE", "/" + index, None)
        except HTTPError as error:
            if error.code != 404:
                raise
        es.request("DELETE", "/_index_template/" + prefix, None)


if __name__ == "__main__":
    main()
